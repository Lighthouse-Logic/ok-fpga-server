#[cfg(test)]
mod tests {
    use super::*;

    /// Verify that the generated bindings contain the `ok_ErrorCode` enum
    /// and that the `ok_NoError` variant has value 0.
    ///
    /// This test catches build.rs misconfiguration — if bindgen fails to
    /// parse the header correctly, this enum won't exist or will have
    /// wrong values.
    #[test]
    fn error_code_enum_has_no_error_variant() {
        // ok_NoError should be 0 in the C header.
        // If this doesn't compile, bindgen failed to generate the enum.
        let code = ok_ErrorCode::ok_NoError;
        assert_eq!(code as i32, 0);
    }

    /// Verify that the okTDeviceInfo struct was generated and has the
    /// expected size. This struct is 574 bytes in the C header (based on
    /// its field layout with fixed-size char arrays).
    #[test]
    fn device_info_struct_exists() {
        // If this doesn't compile, bindgen failed to generate okTDeviceInfo.
        let info = okTDeviceInfo::default();
        // The serial number field should be an array of 11 bytes
        // (10 chars + null terminator).
        assert_eq!(info.serialNumber.len(), 11);
        // The deviceID field should be an array of 33 bytes
        // (32 chars + null terminator).
        assert_eq!(info.deviceID.len(), 33);
    }

    /// Verify that the C function type signatures are present in the bindings.
    ///
    /// Since we use `libloading` for runtime DLL loading (Phase 3B), we
    /// don't link against the DLL at compile time. We verify function
    /// *declarations* exist by confirming the type of the extern function
    /// pointer is recognized by the compiler. The actual function loading
    /// and calling is tested in Phase 3B's `FrontPanelDll` struct.
    ///
    /// This test only checks that the extern declaration compiles — we use
    /// `std::ptr::addr_of!` to reference the symbol without the linker
    /// needing to resolve it.
    #[test]
    fn key_function_types_exist() {
        // If bindgen's allowlist excluded these, the types below would not
        // exist and this test would fail to compile.
        //
        // We verify the *type* of the function pointer, not the function
        // itself. The function signatures are declared by bindgen but
        // resolved at runtime by libloading.
        fn _check_signatures() {
            // These type aliases confirm the function signatures exist.
            // They will cause a compile error if bindgen didn't generate them.
            type ConstructFn = unsafe extern "C" fn() -> okFrontPanel_HANDLE;
            type DestructFn = unsafe extern "C" fn(okFrontPanel_HANDLE);

            // Suppress unused warnings — the point is compile-time checking.
            let _: Option<ConstructFn> = None;
            let _: Option<DestructFn> = None;
        }
    }

    /// Verify that the ok_BoardModel enum contains entries for our
    /// supported Gen3/USB3/PCIe boards (FX5/FX10/FX20 family).
    #[test]
    fn board_model_has_supported_devices() {
        // These are the Gen3 boards we care about. If bindgen excluded
        // the ok_BoardModel enum or these variants, this won't compile.
        let _xem8320 = ok_BoardModel::ok_brdXEM8320AU25P;

        // Verify the enum variant has a reasonable numeric value (non-zero).
        assert_ne!(_xem8320 as i32, 0, "XEM8320AU25P should not be ok_brdUnknown (0)");
    }

    /// Verify that the okTRegisterEntry struct exists (used for register
    /// read/write operations in the Classic data port).
    #[test]
    fn register_entry_struct_exists() {
        let entry = okTRegisterEntry::default();
        // The struct should have address and data fields.
        assert_eq!(entry.address, 0);
        assert_eq!(entry.data, 0);
    }
}

