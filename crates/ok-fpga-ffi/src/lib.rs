//! # ok-fpga-ffi — Low-Level FFI Bindings to Opal Kelly FrontPanel 6.1.0
//!
//! This crate provides the lowest layer of the ok-FPGA-Server stack. It handles:
//!
//! - **Type generation** via `rust-bindgen`: Parses the C header file
//!   `FrontPanel-6.1.0/okFrontPanel.h` at build time and auto-generates Rust
//!   representations of all C structs, enums, and function signatures.
//!
//! - **Runtime DLL loading** via `libloading`: Loads `okFrontPanel.dll` (Windows)
//!   or `libokFrontPanel.so` (Linux) at runtime rather than linking at compile time.
//!   This allows the server to start gracefully even when the DLL is not present.
//!
//! - **Safe handle wrappers**: All C opaque handles (e.g., `okFrontPanel_HANDLE`,
//!   `okDeviceSettings_HANDLE`) are wrapped in Rust structs that automatically
//!   call the corresponding `*_Destruct()` function when dropped. This is the
//!   RAII (Resource Acquisition Is Initialization) pattern.
//!
//! ## Safety Boundary
//!
//! All `unsafe` code in the entire project is confined to this crate. Higher
//! layers (`ok-fpga-core`, `ok-fpga-server`) never use `unsafe` directly.
//!
//! ## Excluded APIs
//!
//! The following FrontPanel functions are excluded because they only work on
//! USB 2.0 devices, which this project does not support:
//! - `okFrontPanel_WriteI2C` / `okFrontPanel_ReadI2C`
//!
//! The Lua scripting API (`okBuffer_*`, `okScriptValue_*`, `okScriptEngine_*`)
//! is also excluded as it is not needed for the server.
//!
//! ## Generated Bindings
//!
//! The `bindings` module below is auto-generated by `rust-bindgen` from
//! `okFrontPanel.h` at build time. It contains raw C types and function
//! declarations. See `build.rs` for the generation configuration.

// ============================================================================
// Auto-generated bindings from okFrontPanel.h
// ============================================================================
//
// These three #[allow] attributes suppress Rust naming convention warnings
// for the generated C bindings. C uses different naming conventions than Rust:
//   - non_upper_case_globals: C constants like `ok_NoError` use camelCase
//   - non_camel_case_types: C types like `ok_ErrorCode` use snake_case with prefix
//   - non_snake_case: C functions like `okFrontPanel_Construct` use PascalCase
//
// We allow these because the generated code must match the C ABI exactly.
// Renaming would break FFI compatibility.
#![allow(non_upper_case_globals)]
#![allow(non_camel_case_types)]
#![allow(non_snake_case)]
// Suppress warnings about u128 not being FFI-safe — bindgen generates these
// for some platform types but they are never actually used across the FFI boundary.
#![allow(improper_ctypes)]

/// Raw FFI bindings auto-generated by `rust-bindgen` from `okFrontPanel.h`.
///
/// This module contains the direct C-to-Rust type mappings:
/// - Opaque handle types (`okFrontPanel_HANDLE`, `okPLL22150_HANDLE`, etc.)
/// - C structs (`okTDeviceInfo`, `okTDeviceSensor`, `okTRegisterEntry`, etc.)
/// - Enums (`ok_ErrorCode`, `ok_BoardModel`, `ok_Product`, etc.)
/// - C function declarations (all prefixed with `okFrontPanel_`, `okPLL22150_`, etc.)
///
/// **Do not use these types directly in application code.** Instead, use the
/// safe wrapper types provided by this crate's public API (implemented in
/// Phase 3B and 3C of the development roadmap).
mod bindings {
    // The include! macro textually inserts the generated file into this module.
    // The concat! and env! macros build the path to the file at compile time:
    //   $OUT_DIR is set by Cargo to a build-specific output directory.
    include!(concat!(env!("OUT_DIR"), "/okfrontpanel_bindings.rs"));
}

// Re-export everything from the bindings module so users of this crate
// can access the types directly (e.g., `ok_fpga_ffi::okTDeviceInfo`).
pub use bindings::*;

